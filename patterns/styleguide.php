<!-- wp:paragraph -->
<p>Near the southern tip of Spain's Cádiz province, where Europe lunges into the Strait of Gibraltar as if reaching out for the North African coast, the&nbsp;<a rel="noreferrer noopener" href="https://www.andalucia.org/en/tarifa-natural-spaces-duna-de-bolonia" target="_blank">Duna de Bolonia</a>&nbsp;is one of the continent's largest sand dunes. Rising more than 30m high and sprawling 200m wide, the white mound spills into the azure sea and appears as if someone has dumped a massive pile of sugar atop the surrounding&nbsp;<a rel="noreferrer noopener" href="https://www.andalucia.org/en/natural-spaces-del-estrecho" target="_blank">Estrecho Nature Park</a>'s protected green forest.</p>
