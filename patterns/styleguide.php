<h3>Heading level 3</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Like all sand dunes, Bolonia is a constantly moving ecosystem that shifts with the winds. But as climate change has intensified the hurricane-force gusts coming from the east, the dune has increasingly migrated inland towards the ecologically important cork and pine forests and scrubland – revealing remnants of the many past cilivilisations who have passed through here in the process.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":4} -->
<h4>Heading level 4</h4>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>In recent years, archaeological excavations have identified ancient burial tombs that were once hidden deep within the dune's depths. Experts aren't sure just how many chambers lie underneath, but because the sand has helped to preserve bones and the structure's foundation, the necropolis remains remarkably intact, yielding artefacts like jewellery and arrowheads.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":5} -->
<h5>Heading level 5</h5>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Nearby, the&nbsp;<a rel="noreferrer noopener" href="https://www.andalucia.org/en/tarifa-cultural-tourism-conjunto-arqueologico-de-baelo-claudia" target="_blank">Baelo Claudia</a>&nbsp;archaeological site dates to the 2nd Century BCE and is one of Spain's best-preserved Roman settlements. Complete with ancient baths, a theatre, temple, forum, aqueducts and sweeping views towards Morocco, the site was built atop a previous Phoenician settlement and was one of the empire's major sources of&nbsp;<a rel="noreferrer noopener" href="https://www.bbc.com/travel/article/20171011-the-ancient-condiment-that-came-back-from-the-dead" target="_blank"><em>garum</em></a>&nbsp;fish sauce production. After a 3rd-Century CE earthquake, the settlement was gradually abandoned, only to be discovered many centuries later under the sand.</p>
